// src/loansDb.js — Supabase layer for the Loans tab.
// Never throws on load: if the table hasn't been created yet it returns ready:false
// so the rest of the app keeps working and the tab can show the setup SQL.
import { supabase } from './supabase.js';

export const LOANS_SETUP_SQL = `create table if not exists loan_entries (
  id bigint generated by default as identity primary key,
  entry_date date not null,
  kind text not null,              -- 'received' | 'direct' | 'repayment'
  lender text not null,
  amount numeric not null,
  bank_txn_id text,                -- set when a bank-statement receipt is marked as a loan
  vendor_name text,                -- set when the lender paid a vendor directly
  project_id text,
  project_payment_id text,
  note text,
  created_at timestamptz default now()
);`;

const mapEntry = r => ({
  id: r.id, date: r.entry_date || '', kind: r.kind || 'received', lender: r.lender || '',
  amount: +r.amount || 0, bankTxnId: r.bank_txn_id ?? null,
  vendorName: r.vendor_name || '', projectId: r.project_id ?? null,
  projectPaymentId: r.project_payment_id ?? null, note: r.note || '',
});

export async function loadLoans() {
  const { data, error } = await supabase.from('loan_entries').select('*')
    .order('entry_date', { ascending: false }).order('id', { ascending: false });
  if (error) return { entries: [], ready: false, error: error.message || String(error) };
  return { entries: (data || []).map(mapEntry), ready: true, error: '' };
}

export async function saveLoanEntry(d) {
  const row = {
    entry_date: d.date, kind: d.kind, lender: (d.lender || '').trim(), amount: +d.amount,
    bank_txn_id: d.bankTxnId != null ? String(d.bankTxnId) : null,
    vendor_name: (d.vendorName || '').trim() || null,
    project_id: d.projectId != null ? String(d.projectId) : null,
    project_payment_id: d.projectPaymentId != null ? String(d.projectPaymentId) : null,
    note: (d.note || '').trim() || null,
  };
  const { data, error } = await supabase.from('loan_entries').insert(row).select().single();
  if (error) throw error;
  return mapEntry(data);
}

export async function deleteLoanEntry(id) {
  const { error } = await supabase.from('loan_entries').delete().eq('id', id);
  if (error) throw error;
}

export async function updateLoanEntry(id, d) {
  const row = {
    entry_date: d.date, lender: (d.lender || '').trim(), amount: +d.amount,
    vendor_name: (d.vendorName || '').trim() || null,
    project_id: d.projectId != null ? String(d.projectId) : null,
    project_payment_id: d.projectPaymentId != null ? String(d.projectPaymentId) : null,
    note: (d.note || '').trim() || null,
  };
  const { data, error } = await supabase.from('loan_entries').update(row).eq('id', id).select().single();
  if (error) throw error;
  return mapEntry(data);
}
