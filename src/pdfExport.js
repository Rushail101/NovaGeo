// pdfExport.js
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

const COMPANY = "Nova Geo Resources LLP";
const TAGLINE = "Ball Mill Processing Plant — Telangana";

// jsPDF's built-in fonts have no ₹ glyph — it renders as garbage (that
// superscript "1") and miscalculates string width, which is what was
// cutting the Amount/NBV columns short. Swap it for plain text first.
function rupeeSafe(val) {
  if (val == null) return val;
  return String(val).replace(/\u20B9/g, "Rs. ");
}

export function exportStatementPDF({ title, subtitle, summary = [], columns, rows, fileName }) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 40;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text(COMPANY, 40, y);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(120);
  doc.text(TAGLINE, 40, y + 14);
  doc.setTextColor(0);
  doc.text(new Date().toLocaleDateString("en-IN"), pageWidth - 40, y, { align: "right" });
  y += 34;
  doc.setDrawColor(210);
  doc.line(40, y, pageWidth - 40, y);
  y += 24;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.text(rupeeSafe(title), 40, y);
  y += 18;
  if (subtitle) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.setTextColor(90);
    doc.text(rupeeSafe(subtitle), 40, y);
    doc.setTextColor(0);
    y += 18;
  }
  y += 6;

  if (summary.length) {
    const colW = (pageWidth - 80) / summary.length;
    summary.forEach((s, i) => {
      const x = 40 + i * colW;
      doc.setFontSize(8);
      doc.setTextColor(130);
      doc.text(rupeeSafe(s.label).toUpperCase(), x, y);
      doc.setFontSize(11);
      doc.setFont("helvetica", "bold");
      if (s.color) doc.setTextColor(...s.color);
      doc.text(rupeeSafe(s.value), x, y + 14);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(0);
    });
    y += 34;
  }

  autoTable(doc, {
    startY: y,
    head: [columns.map(c => rupeeSafe(c.label))],
    body: rows.map(r => columns.map(c => rupeeSafe(r[c.key] ?? "—"))),
    styles: { fontSize: 9, cellPadding: 6, overflow: "linebreak" },
    headStyles: { fillColor: [25, 25, 25], textColor: 255 },
    alternateRowStyles: { fillColor: [247, 247, 247] },
    columnStyles: columns.reduce(
      (acc, c, i) => (c.align === "right" ? { ...acc, [i]: { halign: "right", minCellWidth: 78 } } : acc),
      {}
    ),
    margin: { left: 40, right: 40 },
  });

  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text("Generated by Finance ERP — Nova Geo Resources", 40, doc.internal.pageSize.getHeight() - 20);

  doc.save(fileName || `${title.replace(/[^\w]+/g, "_")}.pdf`);
}

// ── Vendor summary report ─────────────────────────────────────────────────────
// vendors: [{ vendor, contracted, paid, due, projects: [{ projectNo, title, hasValue,
//   contractValue, paid, due, payments: [{ date, source, particulars, amount }] }] }]
// All money values are plain numbers; formatting happens here.
export function exportVendorSummaryPDF({ vendors, withTransactions = false, plannedExpenses = null, subtitle = "", fileName }) {
  const money = n =>
    "Rs. " + (+n || 0).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  let y = 40;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text(COMPANY, 40, y);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(120);
  doc.text(TAGLINE, 40, y + 14);
  doc.setTextColor(0);
  doc.text(new Date().toLocaleDateString("en-IN"), pageWidth - 40, y, { align: "right" });
  y += 34;
  doc.setDrawColor(210);
  doc.line(40, y, pageWidth - 40, y);
  y += 24;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.text("Vendor Summary", 40, y);
  y += 18;
  if (subtitle) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.setTextColor(90);
    doc.text(rupeeSafe(subtitle), 40, y);
    doc.setTextColor(0);
    y += 18;
  }
  y += 6;

  const totals = vendors.reduce(
    (a, v) => ({ contracted: a.contracted + v.contracted, paid: a.paid + v.paid, deducted: a.deducted + (v.deducted || 0), due: a.due + v.due }),
    { contracted: 0, paid: 0, deducted: 0, due: 0 }
  );

  // 1) Overview — one row per project, so a vendor with several projects keeps them separate.
  const R = c => ({ content: c, styles: { halign: "right" } });
  const projectRows = [];
  vendors.forEach(v => v.projects.forEach(p => projectRows.push([
    rupeeSafe(v.vendor),
    rupeeSafe(`${p.projectNo} - ${p.title}`),
    R(p.hasValue ? money(p.contractValue) : "Open-ended"),
    R(money(p.paid)),
    R(money(p.deducted || 0)),
    R(p.hasValue ? money(p.due) : "-"),
  ])));

  autoTable(doc, {
    startY: y,
    head: [["Vendor", "Project", R("Total"), R("Paid"), R("Deducted"), R("Left")]],
    body: projectRows,
    foot: [["TOTAL", `${projectRows.length} project(s)`, R(money(totals.contracted)), R(money(totals.paid)), R(money(totals.deducted)), R(money(totals.due))]],
    showFoot: "lastPage",
    styles: { fontSize: 9, cellPadding: 6, overflow: "linebreak" },
    headStyles: { fillColor: [25, 25, 25], textColor: 255 },
    footStyles: { fillColor: [235, 235, 235], textColor: 20, fontStyle: "bold" },
    alternateRowStyles: { fillColor: [247, 247, 247] },
    columnStyles: {
      2: { halign: "right", minCellWidth: 78 },
      3: { halign: "right", minCellWidth: 78 },
      4: { halign: "right", minCellWidth: 70 },
      5: { halign: "right", minCellWidth: 78 },
    },
    margin: { left: 40, right: 40 },
  });

  doc.setFontSize(8);
  doc.setTextColor(120);
  doc.text(
    "Total = contract value. Paid = payments to the vendor. Deducted = paid to others on the vendor's behalf. Left = Total - Paid - Deducted.",
    40, doc.lastAutoTable.finalY + 14, { maxWidth: pageWidth - 80 }
  );
  doc.setTextColor(0);

  // 2) Optional — every vendor with its projects and payments.
  if (withTransactions) {
    doc.addPage();
    doc.setFont("helvetica", "bold");
    doc.setFontSize(13);
    doc.text("Transaction Details", 40, 50);

    const body = [];
    const span = (content, styles) => ({ content, colSpan: 4, styles });
    vendors.forEach(v => {
      body.push([span(
        `${rupeeSafe(v.vendor)}   |   Total ${money(v.contracted)}   |   Paid ${money(v.paid)}   |   Deducted ${money(v.deducted || 0)}   |   Left ${money(v.due)}`,
        { fillColor: [25, 25, 25], textColor: 255, fontStyle: "bold" }
      )]);
      v.projects.forEach(p => {
        body.push([span(
          `${rupeeSafe(p.projectNo)} - ${rupeeSafe(p.title)}   (${p.hasValue ? `Contract ${money(p.contractValue)}` : "Open-ended"}, Paid ${money(p.paid)}${p.deducted ? `, Deducted ${money(p.deducted)}` : ""}${p.hasValue ? `, Left ${money(p.due)}` : ""})`,
          { fillColor: [225, 232, 240], fontStyle: "bold" }
        )]);
        if (!p.payments.length) {
          body.push([span("No payments linked yet", { textColor: 130, fontStyle: "italic" })]);
        } else {
          p.payments.forEach(x => body.push([rupeeSafe(x.date || ""), rupeeSafe(x.source || ""), rupeeSafe(x.particulars || ""), { content: money(x.amount), styles: { halign: "right" } }]));
        }
      });
    });

    autoTable(doc, {
      startY: 62,
      head: [["Date", "Source", "Particulars", { content: "Amount", styles: { halign: "right" } }]],
      body,
      styles: { fontSize: 8.5, cellPadding: 5, overflow: "linebreak" },
      headStyles: { fillColor: [60, 60, 60], textColor: 255 },
      columnStyles: { 0: { cellWidth: 62 }, 1: { cellWidth: 92 }, 3: { cellWidth: 86 } },
      margin: { left: 40, right: 40 },
    });
  }

  // 3) Optional combined funding forecast: keep estimates separate from actual vendor commitments.
  if (plannedExpenses) {
    doc.addPage();
    let fy = 44;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(14);
    doc.text(COMPANY, 40, fy);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(120);
    doc.text(TAGLINE, 40, fy + 14);
    doc.text(new Date().toLocaleDateString("en-IN"), pageWidth - 40, fy, { align: "right" });
    doc.setTextColor(0);
    fy += 38;
    doc.setDrawColor(210);
    doc.line(40, fy, pageWidth - 40, fy);
    fy += 24;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(15);
    doc.text("Combined Funding Forecast", 40, fy);
    fy += 18;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(90);
    doc.text("Existing vendor project balances plus independent planned purchases and future costs.", 40, fy);
    doc.setTextColor(0);
    fy += 28;

    const plannedTotal = +plannedExpenses.total || 0;
    const vendorBalance = +totals.due || 0;
    const combinedRequired = vendorBalance + plannedTotal;
    const cards = [
      { label: "VENDOR PROJECT BALANCE", value: money(vendorBalance) },
      { label: "PLANNED FUTURE COSTS", value: money(plannedTotal) },
      { label: "COMBINED FUNDING INDICATION", value: money(combinedRequired) },
    ];
    const cardW = (pageWidth - 80 - 20) / 3;
    cards.forEach((c, i) => {
      const x = 40 + i * (cardW + 10);
      doc.setDrawColor(220);
      doc.roundedRect(x, fy, cardW, 48, 4, 4);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(7);
      doc.setTextColor(110);
      doc.text(c.label, x + 8, fy + 13, { maxWidth: cardW - 16 });
      doc.setFont("helvetica", "bold");
      doc.setFontSize(10);
      doc.setTextColor(25);
      doc.text(c.value, x + 8, fy + 33, { maxWidth: cardW - 16 });
    });
    fy += 66;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.text("Planned Expenses", 40, fy);
    fy += 10;
    const plannedRows = (plannedExpenses.items || []).map(x => [
      rupeeSafe(x.itemName || "—"),
      rupeeSafe(x.category || "Other"),
      rupeeSafe(x.vendorName || "Not selected"),
      rupeeSafe(x.expectedDate || "—"),
      rupeeSafe(x.status || "Considering"),
      money(x.estimatedAmount),
    ]);
    autoTable(doc, {
      startY: fy,
      head: [["Planned item", "Category", "Possible vendor", "Expected by", "Status", "Estimate"]],
      body: plannedRows.length ? plannedRows : [[{ content: "No active planned expenses", colSpan: 6, styles: { halign: "center", textColor: 120 } }]],
      foot: [[{ content: "TOTAL ACTIVE PLANNED COST", colSpan: 5, styles: { fontStyle: "bold" } }, { content: money(plannedTotal), styles: { halign: "right", fontStyle: "bold" } }]],
      showFoot: "lastPage",
      styles: { fontSize: 8, cellPadding: 5, overflow: "linebreak" },
      headStyles: { fillColor: [25, 25, 25], textColor: 255 },
      footStyles: { fillColor: [235, 235, 235], textColor: 20 },
      alternateRowStyles: { fillColor: [247, 247, 247] },
      columnStyles: { 0: { cellWidth: 125 }, 1: { cellWidth: 80 }, 2: { cellWidth: 90 }, 3: { cellWidth: 62 }, 4: { cellWidth: 65 }, 5: { halign: "right", cellWidth: 75 } },
      margin: { left: 40, right: 40 },
    });
    const noteY = Math.min((doc.lastAutoTable?.finalY || fy) + 16, pageHeight - 48);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(100);
    doc.text("Planning estimate only. Planned costs are not actual expenses or accounting liabilities. The combined figure is an indicative funding view and excludes any unrecorded costs, financing assumptions or adjustments.", 40, noteY, { maxWidth: pageWidth - 80 });
    doc.setTextColor(0);
  }

  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text("Generated by Finance ERP — Nova Geo Resources", 40, pageHeight - 20);
    doc.text(`Page ${i} of ${pages}`, pageWidth - 40, pageHeight - 20, { align: "right" });
  }

  doc.save(fileName || "vendor_summary.pdf");
}

// Independent future-cost forecast. These rows are estimates only and are not actual accounting entries.
export function exportPlannedExpensesPDF({ items = [], total = 0, committed = 0, fileName = "planned_expenses.pdf" } = {}) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const money = n => "Rs. " + (+n || 0).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  let y = 42;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text(COMPANY, 40, y);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(120);
  doc.text(TAGLINE, 40, y + 14);
  doc.text(new Date().toLocaleDateString("en-IN"), pageWidth - 40, y, { align: "right" });
  doc.setTextColor(0);
  y += 36;
  doc.setDrawColor(210);
  doc.line(40, y, pageWidth - 40, y);
  y += 24;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text("Planned Expenses & Funding Forecast", 40, y);
  y += 20;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(90);
  doc.text("Approximate future costs for purchases, equipment and projects not yet finalized.", 40, y);
  y += 28;

  const summary = [
    { label: "TOTAL PLANNED FUNDING", value: money(total) },
    { label: "APPROVED / COMMITTED", value: money(committed) },
    { label: "ACTIVE ITEMS", value: String(items.length) },
  ];
  const boxW = (pageWidth - 80 - 20) / 3;
  summary.forEach((s, i) => {
    const x = 40 + i * (boxW + 10);
    doc.setDrawColor(220);
    doc.roundedRect(x, y, boxW, 45, 4, 4);
    doc.setFontSize(7.5);
    doc.setTextColor(120);
    doc.text(s.label, x + 8, y + 13);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(25);
    doc.text(rupeeSafe(s.value), x + 8, y + 31, { maxWidth: boxW - 16 });
    doc.setFont("helvetica", "normal");
  });
  y += 62;

  const rows = items.map(x => [
    rupeeSafe(x.itemName || "—"),
    rupeeSafe(x.category || "Other"),
    rupeeSafe(x.vendorName || "Not selected"),
    rupeeSafe(x.expectedDate || "—"),
    rupeeSafe(x.status || "Considering"),
    money(x.estimatedAmount),
  ]);
  autoTable(doc, {
    startY: y,
    head: [["Planned item", "Category", "Possible vendor", "Expected by", "Status", "Estimate"]],
    body: rows,
    foot: [[{ content: "TOTAL ACTIVE PLANNED COST", colSpan: 5, styles: { fontStyle: "bold" } }, { content: money(total), styles: { halign: "right", fontStyle: "bold" } }]],
    showFoot: "lastPage",
    styles: { fontSize: 8, cellPadding: 5, overflow: "linebreak" },
    headStyles: { fillColor: [25, 25, 25], textColor: 255 },
    footStyles: { fillColor: [235, 235, 235], textColor: 20 },
    alternateRowStyles: { fillColor: [247, 247, 247] },
    columnStyles: { 0: { cellWidth: 125 }, 1: { cellWidth: 80 }, 2: { cellWidth: 90 }, 3: { cellWidth: 62 }, 4: { cellWidth: 65 }, 5: { halign: "right", cellWidth: 75 } },
    margin: { left: 40, right: 40 },
  });

  const noteY = Math.min((doc.lastAutoTable?.finalY || y) + 18, pageHeight - 58);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(100);
  const note = "Planning report only. Amounts are approximate and may change after quotations, vendor selection, taxes and installation costs are confirmed. Cancelled items are excluded. These figures are not actual expenses, purchase orders, liabilities or accounting entries. Add real transactions to the relevant accounting module when incurred.";
  doc.text(note, 40, noteY, { maxWidth: pageWidth - 80 });

  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text("Generated by Finance ERP — Nova Geo Resources", 40, pageHeight - 20);
    doc.text(`Page ${i} of ${pages}`, pageWidth - 40, pageHeight - 20, { align: "right" });
  }
  doc.save(fileName);
}
