// pdfExport.js
// Generates a properly formatted, standalone PDF for a single statement
// (vendor ledger, partner capital account, etc.) instead of printing the
// whole app UI via window.print().
//
// npm install jspdf jspdf-autotable

import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

const COMPANY = "Nova Geo Resources LLP";
const TAGLINE = "Ball Mill Processing Plant — Telangana";

/**
 * @param {Object} opts
 * @param {string} opts.title        e.g. "Statement of Account: Mateshwari Industries"
 * @param {string} [opts.subtitle]   e.g. "Category: vendor"
 * @param {{label:string, value:string, color?:[number,number,number]}[]} [opts.summary]
 *        Short key figures shown as a strip under the title (paid/due/net standing etc.)
 * @param {{key:string, label:string, align?:"right"}[]} opts.columns
 * @param {Object[]} opts.rows       plain objects keyed to `columns[].key`, already
 *                                   formatted as display strings (run fmt()/dates first)
 * @param {string} [opts.fileName]
 */
export function exportStatementPDF({ title, subtitle, summary = [], columns, rows, fileName }) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 40;

  // ── Letterhead ──
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text(COMPANY, 40, y);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(120);
  doc.text(TAGLINE, 40, y + 14);
  doc.setTextColor(0);
  doc.text(new Date().toLocaleDateString("en-IN"), pageWidth - 40, y, { align: "right" });
  y += 34;
  doc.setDrawColor(210);
  doc.line(40, y, pageWidth - 40, y);
  y += 24;

  // ── Title block ──
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.text(title, 40, y);
  y += 18;
  if (subtitle) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.setTextColor(90);
    doc.text(subtitle, 40, y);
    doc.setTextColor(0);
    y += 18;
  }
  y += 6;

  // ── Summary strip ──
  if (summary.length) {
    const colW = (pageWidth - 80) / summary.length;
    summary.forEach((s, i) => {
      const x = 40 + i * colW;
      doc.setFontSize(8);
      doc.setTextColor(130);
      doc.text(s.label.toUpperCase(), x, y);
      doc.setFontSize(11);
      doc.setFont("helvetica", "bold");
      if (s.color) doc.setTextColor(...s.color);
      doc.text(s.value, x, y + 14);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(0);
    });
    y += 34;
  }

  // ── Table ──
  autoTable(doc, {
    startY: y,
    head: [columns.map(c => c.label)],
    body: rows.map(r => columns.map(c => (r[c.key] ?? "—"))),
    styles: { fontSize: 9, cellPadding: 6 },
    headStyles: { fillColor: [25, 25, 25], textColor: 255 },
    alternateRowStyles: { fillColor: [247, 247, 247] },
    columnStyles: columns.reduce(
      (acc, c, i) => (c.align === "right" ? { ...acc, [i]: { halign: "right" } } : acc),
      {}
    ),
    margin: { left: 40, right: 40 },
  });

  // ── Footer ──
  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text(
    "Generated by BallMill ERP — Nova Geo Resources",
    40,
    doc.internal.pageSize.getHeight() - 20
  );

  doc.save(fileName || `${title.replace(/[^\w]+/g, "_")}.pdf`);
}
