-- Nova Geo Finance ERP — 003_capital_projects.sql
-- Tables behind Capital & Infra › "Projects & Dues" (machinery / civil work paid
-- in instalments). The screen existed before but had no tables or save code,
-- so saving a project failed. Run after 001_security.sql. Safe to re-run.
-- ============================================================================
create table if not exists capital_projects (
  id          bigint generated by default as identity primary key,
  project_no  text,
  p_date      date not null,
  category    text default 'machinery',
  vendor_name text not null,
  description text,
  total_cost  numeric not null default 0,
  reference   text,
  created_at  timestamptz not null default now()
);

create table if not exists capital_project_payments (
  id           bigint generated by default as identity primary key,
  project_id   bigint not null references capital_projects(id) on delete cascade,
  pay_date     date not null,
  amount       numeric not null check (amount >= 0),
  payment_mode text default 'bank',
  bank_txn_id  text,
  reference    text,
  remarks      text,
  created_at   timestamptz not null default now()
);
create index if not exists capital_project_payments_proj_idx on capital_project_payments (project_id);

-- Readable project numbers: CP-0001, CP-0002 …
create or replace function capital_project_no() returns trigger
language plpgsql as $$
begin
  if new.project_no is null then new.project_no := 'CP-' || lpad(new.id::text, 4, '0'); end if;
  return new;
end $$;
drop trigger if exists capital_project_no on capital_projects;
create trigger capital_project_no before insert on capital_projects
  for each row execute function capital_project_no();

do $$ begin perform fin_secure_table(t) from unnest(array['capital_projects','capital_project_payments']) as t; end $$;
