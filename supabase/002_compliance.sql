-- Consecutive numbering per financial year (GST: max 16 characters, unique in the FY).
-- Uses the India date, so 1 April after midnight IST starts the new series.
create or replace function next_sales_doc_no(p_doc_type text, p_date date) returns text
language plpgsql security definer set search_path = public as $$
declare
  v_fy text; v_seq int; v_pre text; v_tag text;
begin
  if not fin_can_write() then raise exception 'Not allowed'; end if;
  v_fy := case when extract(month from p_date) >= 4
             then extract(year from p_date)::int::text || '-' || right((extract(year from p_date)::int + 1)::text, 2)
             else (extract(year from p_date)::int - 1)::text || '-' || right(extract(year from p_date)::int::text, 2) end;
  v_pre := coalesce(nullif((select data->>'invoice_prefix' from company_settings where id = 1), ''), 'NGR');
  v_tag := case p_doc_type when 'credit_note' then 'CN' when 'debit_note' then 'DN' else '' end;
  perform pg_advisory_xact_lock(hashtext('nova_sales_' || p_doc_type || v_fy));
  select coalesce(max((regexp_match(s.invoice_no, '([0-9]+)$'))[1]::int), 0) + 1 into v_seq
    from sales_invoices s where s.doc_type = p_doc_type and s.fy = v_fy;
  return v_pre || v_tag || '/' || right(v_fy, 5) || '/' || lpad(v_seq::text, 4, '0');   -- e.g. NGR/26-27/0001 (14 chars)
end $$;
revoke execute on function next_sales_doc_no(text, date) from anon, public;
grant execute on function next_sales_doc_no(text, date) to authenticated;

-- Issued invoices keep their number and amounts; only admins can change a cancelled one back.
create or replace function sales_invoice_guard() returns trigger
language plpgsql as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'draft' then raise exception 'Issued invoices cannot be deleted. Cancel it instead (the number stays used).'; end if;
    return old;
  end if;
  if old.status = 'cancelled' and not fin_is_admin() then
    raise exception 'This invoice is cancelled. Only an admin can change it.';
  end if;
  if old.status = 'issued' and new.invoice_no <> old.invoice_no then
    raise exception 'The number of an issued invoice cannot change.';
  end if;
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists sales_invoice_guard on sales_invoices;
create trigger sales_invoice_guard before update or delete on sales_invoices
  for each row execute function sales_invoice_guard();

