-- ============================================================================
-- Nova Geo Finance ERP — 001_security.sql
-- Locks the finance database down to signed-in, approved users and adds an
-- audit trail. Safe to re-run.
--
-- BEFORE this script, anyone with the site URL could read and change every
-- table (the anon key is inside the website's JavaScript). After it, only
-- people listed in fin_users with an active role can see or change data.
--
-- Run in Supabase > SQL editor, in one go. Then:
--   1. Open the app and create your account on the sign-in screen.
--      The FIRST account created becomes admin automatically.
--   2. Everyone else who signs up lands as "pending" until the admin
--      approves them under Admin > Users.
--   3. (Recommended) Authentication > Providers > Email: keep "Confirm email" ON.
-- ============================================================================

-- ---------- 1. Users and roles ----------------------------------------------
create table if not exists fin_users (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  email      text,
  name       text,
  role       text not null default 'pending'
             check (role in ('admin','accountant','viewer','pending')),
  active     boolean not null default true,
  created_at timestamptz not null default now()
);

-- Role of the current user ('' when not signed in / not approved / blocked)
create or replace function fin_role() returns text
language sql stable security definer set search_path = public as $$
  select coalesce((select role from fin_users where user_id = auth.uid() and active), '')
$$;

create or replace function fin_can_read() returns boolean
language sql stable as $$ select fin_role() in ('admin','accountant','viewer') $$;

create or replace function fin_can_write() returns boolean
language sql stable as $$ select fin_role() in ('admin','accountant') $$;

create or replace function fin_is_admin() returns boolean
language sql stable as $$ select fin_role() = 'admin' $$;

-- New sign-ups: first one is admin, the rest wait for approval
create or replace function fin_on_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into fin_users (user_id, email, name, role)
  values (
    new.id, new.email,
    coalesce(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    case when exists (select 1 from fin_users where role = 'admin') then 'pending' else 'admin' end
  )
  on conflict (user_id) do nothing;
  return new;
end $$;

drop trigger if exists fin_on_new_user on auth.users;
create trigger fin_on_new_user after insert on auth.users
  for each row execute function fin_on_new_user();

-- Accounts that existed before this script
insert into fin_users (user_id, email, name, role)
select u.id, u.email, split_part(u.email, '@', 1), 'pending'
from auth.users u
on conflict (user_id) do nothing;
-- If nobody is admin yet, promote the oldest account
update fin_users set role = 'admin'
where user_id = (select user_id from fin_users order by created_at limit 1)
  and not exists (select 1 from fin_users where role = 'admin');

alter table fin_users enable row level security;
drop policy if exists "fin_users read"   on fin_users;
drop policy if exists "fin_users admin"  on fin_users;
create policy "fin_users read"  on fin_users for select to authenticated
  using (user_id = auth.uid() or fin_is_admin());
create policy "fin_users admin" on fin_users for update to authenticated
  using (fin_is_admin()) with check (fin_is_admin());

-- An admin cannot demote / block the last active admin (prevents lock-out)
create or replace function fin_keep_one_admin() returns trigger
language plpgsql as $$
begin
  if old.role = 'admin' and old.active and (new.role <> 'admin' or not new.active)
     and (select count(*) from fin_users where role = 'admin' and active) <= 1 then
    raise exception 'At least one active admin is required';
  end if;
  return new;
end $$;
drop trigger if exists fin_keep_one_admin on fin_users;
create trigger fin_keep_one_admin before update on fin_users
  for each row execute function fin_keep_one_admin();

-- ---------- 2. Audit trail ---------------------------------------------------
create table if not exists fin_audit_log (
  id         bigint generated by default as identity primary key,
  at         timestamptz not null default now(),
  user_id    uuid default auth.uid(),
  user_email text,
  table_name text not null,
  action     text not null,          -- INSERT / UPDATE / DELETE
  row_id     text,
  old_data   jsonb,
  new_data   jsonb
);
create index if not exists fin_audit_log_at_idx on fin_audit_log (at desc);
create index if not exists fin_audit_log_tbl_idx on fin_audit_log (table_name, row_id);

create or replace function fin_audit() returns trigger
language plpgsql security definer set search_path = public as $$
declare r jsonb := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
begin
  insert into fin_audit_log (user_id, user_email, table_name, action, row_id, old_data, new_data)
  values (
    auth.uid(),
    (select email from fin_users where user_id = auth.uid()),
    tg_table_name, tg_op, r->>'id',
    case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) end,
    case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) end
  );
  return null;
end $$;

alter table fin_audit_log enable row level security;
drop policy if exists "audit read" on fin_audit_log;
create policy "audit read" on fin_audit_log for select to authenticated using (fin_is_admin());
-- No insert/update/delete policy: rows are written only by the trigger and cannot be edited.

-- ---------- 3. Lock every finance table --------------------------------------
-- fin_secure_table(name): removes every old policy on the table (including the
-- old "anyone" ones), turns RLS on, and adds read/write/audit for approved users.
-- Later migrations call it for their new tables too.
create or replace function fin_secure_table(t text) returns void
language plpgsql as $$
declare p record;
begin
  if to_regclass('public.' || t) is null then return; end if;
  for p in select policyname from pg_policies where schemaname = 'public' and tablename = t loop
    execute format('drop policy %I on public.%I', p.policyname, t);
  end loop;
  execute format('alter table public.%I enable row level security', t);
  execute format('revoke all on public.%I from anon', t);
  execute format('create policy "fin read"   on public.%I for select to authenticated using (fin_can_read())', t);
  execute format('create policy "fin insert" on public.%I for insert to authenticated with check (fin_can_write())', t);
  execute format('create policy "fin update" on public.%I for update to authenticated using (fin_can_write()) with check (fin_can_write())', t);
  execute format('create policy "fin delete" on public.%I for delete to authenticated using (fin_can_write())', t);
  execute format('drop trigger if exists fin_audit on public.%I', t);
  execute format('create trigger fin_audit after insert or update or delete on public.%I for each row execute function fin_audit()', t);
end $$;

do $$ begin
  perform fin_secure_table(t) from unnest(array[
    'suppliers','purchases','expenses','capital_items','capital_projects',
    'bank_import_batches','bank_txns','bank_labels','partner_cashbook',
    'vendor_projects','vendor_project_payments','vendor_project_estimates',
    'planned_expenses','loan_entries','attachments','purchase_orders'
  ]) as t;
end $$;

-- Any other table in public that still has an "open to anon" policy gets locked too
do $$
declare t text;
begin
  for t in
    select distinct tablename from pg_policies
    where schemaname = 'public' and 'anon' = any(roles)
      and tablename not in ('fin_users','fin_audit_log')
  loop
    perform fin_secure_table(t);
  end loop;
end $$;

-- PO number generator: signed-in writers only
do $$ begin
  if to_regproc('public.next_nova_geo_po_number') is not null then
    revoke execute on function public.next_nova_geo_po_number() from anon, public;
    grant execute on function public.next_nova_geo_po_number() to authenticated;
  end if;
end $$;

-- ---------- 4. Bills & documents storage bucket ------------------------------
insert into storage.buckets (id, name, public)
values ('erp-attachments', 'erp-attachments', false)
on conflict (id) do update set public = false;

drop policy if exists "erp attachments access" on storage.objects;
drop policy if exists "erp attachments read"   on storage.objects;
drop policy if exists "erp attachments write"  on storage.objects;
drop policy if exists "erp attachments change" on storage.objects;
drop policy if exists "erp attachments remove" on storage.objects;
create policy "erp attachments read" on storage.objects for select to authenticated
  using (bucket_id = 'erp-attachments' and fin_can_read());
create policy "erp attachments write" on storage.objects for insert to authenticated
  with check (bucket_id = 'erp-attachments' and fin_can_write());
create policy "erp attachments change" on storage.objects for update to authenticated
  using (bucket_id = 'erp-attachments' and fin_can_write());
create policy "erp attachments remove" on storage.objects for delete to authenticated
  using (bucket_id = 'erp-attachments' and fin_can_write());

